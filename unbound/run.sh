#!/usr/bin/with-contenv bashio
# shellcheck shell=bash
# ==============================================================================
# Generates unbound.conf from the app options, validates it and starts Unbound
# in the foreground as the unprivileged user "unbound".
#
# Files:
#   /data/conf/unbound.conf   generated on every start (root:unbound 0640)
#   /data/state/root.key      trust anchor, updated by Unbound (RFC 5011)
#   /data/state/root.hints    optional, refreshed from internic.net
#   /config/custom.conf       optional, user-owned, never written by this app;
#                             a read-only copy is placed in /data/conf so the
#                             unprivileged unbound user never needs /config
# ==============================================================================
set -euo pipefail

readonly CONF_DIR=/data/conf
readonly STATE_DIR=/data/state
readonly CONF="${CONF_DIR}/unbound.conf"
readonly ROOT_KEY="${STATE_DIR}/root.key"
readonly ROOT_HINTS="${STATE_DIR}/root.hints"
readonly CUSTOM_CONF=/config/custom.conf
readonly CUSTOM_COPY="${CONF_DIR}/custom.conf"
readonly PORT=5335
readonly ROOT_HINTS_URL="https://www.internic.net/domain/named.root"

# --- reset_config --------------------------------------------------------------
if bashio::config.true 'reset_config'; then
    bashio::log.warning "reset_config is enabled: removing generated files and trust anchor state."
    rm -rf "${CONF_DIR}" "${STATE_DIR}"
    if bashio::app.option 'reset_config' '^false'; then
        bashio::log.info "reset_config has been switched back to false."
    else
        bashio::log.warning "Could not switch reset_config back to false - please disable it manually."
    fi
fi

mkdir -p "${CONF_DIR}" "${STATE_DIR}"
chown root:unbound "${CONF_DIR}"
chmod 0750 "${CONF_DIR}"
chown unbound:unbound "${STATE_DIR}"
chmod 0750 "${STATE_DIR}"

# --- trust anchor ----------------------------------------------------------------
if [[ ! -s "${ROOT_KEY}" ]]; then
    bashio::log.info "Initialising DNSSEC trust anchor from the built-in root keys."
    install -o unbound -g unbound -m 0640 /usr/share/unbound/root.key "${ROOT_KEY}"
fi

# --- root hints ------------------------------------------------------------------
# Unbound has the root server list compiled in. A downloaded copy is only used
# when it passes a sanity check (13 root servers with IPv4 addresses).
if bashio::config.true 'update_root_hints_on_start'; then
    bashio::log.info "Refreshing root hints from ${ROOT_HINTS_URL}"
    tmp_hints="$(mktemp)"
    if curl --proto '=https' --tlsv1.2 -fsS --max-time 15 --max-filesize 65536 \
            -o "${tmp_hints}" "${ROOT_HINTS_URL}" \
        && [[ "$(grep -cE '^[A-M]\.ROOT-SERVERS\.NET\.[[:space:]]+[0-9]+[[:space:]]+A[[:space:]]' "${tmp_hints}")" -eq 13 ]] \
        && grep -qE '^\.[[:space:]]+[0-9]+[[:space:]]+NS[[:space:]]+A\.ROOT-SERVERS\.NET\.' "${tmp_hints}"; then
        install -o unbound -g unbound -m 0640 "${tmp_hints}" "${ROOT_HINTS}"
        bashio::log.info "Root hints updated."
    else
        bashio::log.warning "Root hints download failed or looked invalid; using the previous/built-in list."
    fi
    rm -f "${tmp_hints}"
fi

# --- helpers ----------------------------------------------------------------------
yn() { if bashio::config.true "$1"; then echo yes; else echo no; fi; }

# Values are validated by the option schema; this is a second line of defence
# against characters that could break out of a quoted unbound.conf value.
check_values() {
    local key="$1" value
    while IFS= read -r value; do
        if [[ "${value}" == *'"'* || "${value}" == *"\\"* ]]; then
            bashio::exit.nok "Option '${key}' contains an invalid character (quote or backslash)."
        fi
    done <<< "$(bashio::config "${key}")"
}
for key in access_control private_domains local_data forward_addresses; do
    check_values "${key}"
done
for i in $(bashio::config 'local_zones|keys'); do
    check_values "local_zones[${i}].name"
done

# Print "<prefix><value><suffix>" for every entry of a list option.
emit_list() {
    local key="$1" prefix="$2" suffix="$3" value
    while IFS= read -r value; do
        if [[ -n "${value}" ]]; then
            printf '%s%s%s\n' "${prefix}" "${value}" "${suffix}"
        fi
    done <<< "$(bashio::config "${key}")"
}

threads="$(bashio::config 'num_threads')"
slabs=1
while ((slabs < threads)); do slabs=$((slabs * 2)); done

# --- generate unbound.conf --------------------------------------------------------
tmp_conf="$(mktemp)"
{
    cat <<EOF
# Generated by the Unbound app on every start - do not edit.
# Put your own additions into /config/custom.conf instead.

server:
    # --- process / logging (stdout via stderr, no syslog, no pidfile) ---
    username: ""
    chroot: ""
    directory: "${STATE_DIR}"
    pidfile: ""
    do-daemonize: no
    use-syslog: no
    logfile: ""
    log-time-ascii: yes
    verbosity: $(bashio::config 'verbosity')
    log-queries: $(yn log_queries)
    log-servfail: $(yn log_servfail)

    # --- listening ---
    interface: 0.0.0.0
    port: ${PORT}
    do-ip4: $(yn do_ip4)
    do-ip6: $(yn do_ip6)
    prefer-ip6: no
    do-udp: $(yn do_udp)
    do-tcp: $(yn do_tcp)
    so-reuseport: yes

    # --- access control: refuse everything, then allow configured networks ---
    # (Unbound always allows 127.0.0.0/8 by default - that is only the
    # container itself, used by the health check.)
    access-control: 0.0.0.0/0 refuse
    access-control: ::0/0 refuse
EOF
    emit_list access_control '    access-control: ' ' allow'

    cat <<EOF

    # --- privacy / hardening ---
    hide-identity: yes
    hide-version: yes
    hide-trustanchor: yes
    qname-minimisation: $(yn qname_minimisation)
    aggressive-nsec: $(yn aggressive_nsec)
    harden-glue: $(yn harden_glue)
    harden-dnssec-stripped: $(yn harden_dnssec_stripped)
    harden-below-nxdomain: $(yn harden_below_nxdomain)
    harden-referral-path: $(yn harden_referral_path)
    harden-large-queries: yes
    harden-short-bufsize: yes
    use-caps-for-id: no
    minimal-responses: yes
    deny-any: yes
    val-clean-additional: yes
    # Treat a flood of unsolicited replies as a spoofing attempt.
    unwanted-reply-threshold: 10000000

    # --- abuse protection ---
    # ratelimit: queries/s per upstream zone. ip-ratelimit: queries/s per client
    # IP - AdGuard is usually the only client, so keep it 0 (off) or high.
    ratelimit: $(bashio::config 'ratelimit')
    ip-ratelimit: $(bashio::config 'ip_ratelimit')

    # --- DNSSEC ---
    module-config: "validator iterator"
    auto-trust-anchor-file: "${ROOT_KEY}"

    # --- LTE robustness ---
    # 1232 bytes avoids IP fragmentation (DNS Flag Day 2020); larger answers
    # fall back to TCP, which is why do-tcp should stay enabled.
    edns-buffer-size: $(bashio::config 'edns_buffer_size')
    # Keep probing servers marked as down instead of waiting for the full
    # infra-host-ttl - helps after short mobile network outages.
    infra-keep-probing: yes
    # Unbound defaults, stated explicitly: how long server RTT/lameness
    # information is cached (s) and how long a busy thread keeps a query (ms).
    infra-host-ttl: 900
    jostle-timeout: 200

    # --- cache ---
    num-threads: ${threads}
    msg-cache-slabs: ${slabs}
    rrset-cache-slabs: ${slabs}
    infra-cache-slabs: ${slabs}
    key-cache-slabs: ${slabs}
    msg-cache-size: $(bashio::config 'msg_cache_size_mb')m
    rrset-cache-size: $(bashio::config 'rrset_cache_size_mb')m
    cache-min-ttl: $(bashio::config 'cache_min_ttl')
    cache-max-ttl: $(bashio::config 'cache_max_ttl')
    prefetch: $(yn prefetch)
    prefetch-key: yes
    # RFC 8767 serve-stale: answer from expired cache if upstream is slow/down.
    serve-expired: $(yn serve_expired)
    serve-expired-ttl: 86400
    serve-expired-client-timeout: 1800
EOF

    if [[ -s "${ROOT_HINTS}" ]]; then
        echo "    root-hints: \"${ROOT_HINTS}\""
    fi

    if bashio::config.true 'private_address_protection'; then
        cat <<EOF

    # --- DNS rebinding protection ---
    private-address: 10.0.0.0/8
    private-address: 172.16.0.0/12
    private-address: 192.168.0.0/16
    private-address: 169.254.0.0/16
    private-address: fd00::/8
    private-address: fe80::/10
    private-address: ::ffff:0:0/96
EOF
        emit_list private_domains '    private-domain: "' '"'
    fi

    if bashio::config.has_value 'local_zones'; then
        echo ""
        echo "    # --- local zones ---"
        for i in $(bashio::config 'local_zones|keys'); do
            echo "    local-zone: \"$(bashio::config "local_zones[${i}].name")\" $(bashio::config "local_zones[${i}].type")"
        done
    fi
    emit_list local_data '    local-data: "' '"'

    cat <<EOF

remote-control:
    control-enable: no
EOF

    if bashio::config.true 'forwarding_enabled'; then
        if ! bashio::config.has_value 'forward_addresses'; then
            bashio::exit.nok "forwarding_enabled is true, but forward_addresses is empty."
        fi
        echo ""
        echo "# !!! FORWARDING MODE - not a recursive resolver !!!"
        echo "forward-zone:"
        echo "    name: \".\""
        echo "    forward-first: no"
        emit_list forward_addresses '    forward-addr: ' ''
    fi

    if [[ -f "${CUSTOM_CONF}" ]]; then
        echo ""
        echo "# Copy of ${CUSTOM_CONF} (must start with its own clause, e.g. 'server:')"
        echo "include-toplevel: \"${CUSTOM_COPY}\""
    fi
} > "${tmp_conf}"

rm -f "${CUSTOM_COPY}"
if [[ -f "${CUSTOM_CONF}" ]]; then
    install -o root -g unbound -m 0640 "${CUSTOM_CONF}" "${CUSTOM_COPY}"
fi

install -o root -g unbound -m 0640 "${tmp_conf}" "${CONF}"
rm -f "${tmp_conf}"

# --- mode banner --------------------------------------------------------------
if bashio::config.true 'forwarding_enabled'; then
    bashio::log.warning "################################################################"
    bashio::log.warning "# FORWARDING IS ENABLED - Unbound does NOT resolve recursively. #"
    bashio::log.warning "# All queries are sent to: $(bashio::config 'forward_addresses' | tr '\n' ' ')"
    bashio::log.warning "# Disable 'forwarding_enabled' to return to recursive mode.     #"
    bashio::log.warning "################################################################"
else
    bashio::log.info "Mode: fully recursive (root -> TLD -> authoritative), DNSSEC validating."
fi
if [[ -f "${CUSTOM_CONF}" ]]; then
    bashio::log.info "Including ${CUSTOM_CONF}"
fi

# --- validate ---------------------------------------------------------------------
if ! check_output="$(unbound-checkconf "${CONF}" 2>&1)"; then
    bashio::log.fatal "Configuration check failed:"
    while IFS= read -r line; do bashio::log.fatal "  ${line}"; done <<< "${check_output}"
    if [[ -f "${CUSTOM_CONF}" ]]; then
        bashio::log.fatal "Check ${CUSTOM_CONF} - it is included as-is (errors refer to its copy ${CUSTOM_COPY})."
    fi
    bashio::log.fatal "Unbound was NOT started. Fix the configuration and start the app again."
    exit 1
fi

bashio::log.info "Starting Unbound $(unbound -V | head -n1 | awk '{print $2}') on port ${PORT}"
exec s6-setuidgid unbound /usr/sbin/unbound -d -p -c "${CONF}"
